import { WEBUI_API_BASE_URL } from '$lib/constants';

export const createNewProject = async (token: string, project: object) => {
	let error = null;

	const res = await fetch(`${WEBUI_API_BASE_URL}/projects/create`, {
		method: 'POST',
		headers: {
			Accept: 'application/json',
			'Content-Type': 'application/json',
			authorization: `Bearer ${token}`
		},
		body: JSON.stringify({
			...project
		})
	})
		.then(async (res) => {
			if (!res.ok) throw await res.json();
			return res.json();
		})
		.catch((err) => {
			error = err.detail;
			console.error(err);
			return null;
		});

	if (error) {
		throw error;
	}

	return res;
};

export const getProjects = async (token: string = '', share?: boolean) => {
	let error = null;

	const searchParams = new URLSearchParams();
	if (share !== undefined) {
		searchParams.append('share', String(share));
	}

	const res = await fetch(`${WEBUI_API_BASE_URL}/projects/?${searchParams.toString()}`, {
		method: 'GET',
		cache: 'no-store',
		headers: {
			Accept: 'application/json',
			'Content-Type': 'application/json',
			authorization: `Bearer ${token}`
		}
	})
		.then(async (res) => {
			if (!res.ok) throw await res.json();
			return res.json();
		})
		.then((json) => {
			return json;
		})
		.catch((err) => {
			error = err.detail;
			console.error(err);
			return null;
		});

	if (error) {
		throw error;
	}

	return res;
};

